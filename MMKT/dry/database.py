"""Existing table only. Read-only preflight; INSERT requires --write-db.

Never create/alter tables or delete/update rows. Credentials pass only through
the existing process-internal db_config loader; raw exceptions are not printed.
"""
from __future__ import annotations

import csv
import hashlib
import json
import re
from decimal import Decimal, InvalidOperation
from pathlib import Path

from common.config import db_config
from dry import config
from dry.detail import CollectionError


def file_digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def connect():
    import psycopg2
    settings = db_config()
    if not settings:
        raise CollectionError("DB_CONFIGURATION_MISSING")
    return psycopg2.connect(host=settings.get("host"), port=int(settings.get("port") or 5432),
                            user=settings.get("user"), password=settings.get("password"),
                            dbname=settings.get("database"), connect_timeout=10)


def table_metadata(cursor, table: tuple[str, str]) -> dict:
    cursor.execute(
        "SELECT column_name, data_type, is_nullable, column_default, is_identity, "
        "character_maximum_length, udt_name FROM information_schema.columns "
        "WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position", table)
    return {name: {"type": kind, "nullable": nullable == "YES", "default": default is not None,
                   "identity": identity == "YES", "max_length": length, "udt": udt}
            for name, kind, nullable, default, identity, length, udt in cursor.fetchall()}


def validate_schema(metadata: dict) -> None:
    if not set(config.COLUMNS).issubset(metadata):
        raise CollectionError("DB_REQUIRED_COLUMNS_MISSING")
    id_column = metadata["id"]
    if not (id_column["identity"] or id_column["default"]):
        raise CollectionError("DB_ID_NOT_AUTOGENERATED")
    if any(not value["nullable"] and not value["default"] and not value["identity"]
           for key, value in metadata.items() if key not in config.COLUMNS):
        raise CollectionError("DB_EXTRA_REQUIRED_COLUMN")


def typed_value(value, column: str, metadata: dict):
    if value in (None, ""):
        if not metadata["nullable"]:
            raise CollectionError("DB_REQUIRED_VALUE_MISSING:" + column)
        return None
    kind = metadata["type"]
    if kind in {"smallint", "integer", "bigint", "numeric", "decimal", "real", "double precision"}:
        raw = str(value).strip()
        if column in {"final_sku_price", "original_sku_price"}:
            raw = raw.replace("€", "").replace("\u00a0", "").replace(" ", "")
            if "," in raw:
                raw = raw.replace(".", "").replace(",", ".").replace("–", "00").replace("-", "00")
        elif column == "savings":
            raw = raw.removesuffix("%").replace(",", ".")
        elif column == "capacity":
            raw = re.sub(r"\s*kg$", "", raw, flags=re.I).replace(",", ".")
        try:
            amount = Decimal(raw)
        except InvalidOperation:
            raise CollectionError("DB_NUMERIC_VALUE_INVALID:" + column) from None
        if not amount.is_finite():
            raise CollectionError("DB_NUMERIC_VALUE_INVALID:" + column)
        if kind in {"smallint", "integer", "bigint"}:
            if amount != amount.to_integral_value():
                raise CollectionError("DB_INTEGER_VALUE_INVALID:" + column)
            return int(amount)
        return amount
    if kind in {"text", "character varying", "character"}:
        result = str(value)
        if metadata["max_length"] is not None and len(result) > metadata["max_length"]:
            raise CollectionError("DB_VALUE_TOO_LONG:" + column)
        return result
    if kind in {"timestamp without time zone", "timestamp with time zone", "date"} and column == "crawl_datetime":
        from datetime import datetime
        parsed = datetime.strptime(str(value), "%Y-%m-%d %H:%M:%S")
        if kind == "timestamp with time zone":
            parsed = parsed.astimezone()  # use the AWS host clock zone, just like the crawl
        return parsed.date() if kind == "date" else parsed
    raise CollectionError("DB_COLUMN_TYPE_UNSUPPORTED:" + column)


def load_validated_output(path: Path) -> list[dict]:
    manifest_path = path.parent / "mmkt_dry_manifest.json"
    if not path.is_file() or not manifest_path.is_file():
        raise CollectionError("VALIDATED_OUTPUT_MISSING")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if not manifest.get("success") or manifest.get("output_digest") != file_digest(path):
        raise CollectionError("OUTPUT_NOT_VALIDATED_OR_CHANGED")
    with path.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if tuple(reader.fieldnames or ()) != config.COLUMNS:
            raise CollectionError("OUTPUT_COLUMNS_INVALID")
        rows = list(reader)
    ids = [row["item"] for row in rows]
    if len(ids) != len(set(ids)) or any(not item for item in ids) or len(rows) != manifest.get("output_rows"):
        raise CollectionError("OUTPUT_ROWS_INVALID")
    return rows


def inspect_or_insert(table: tuple[str, str], rows: list[dict] | None = None) -> dict:
    from psycopg2 import sql
    connection = connect()
    try:
        connection.set_session(readonly=rows is None)
        with connection:
            with connection.cursor() as cursor:
                metadata = table_metadata(cursor, table)
                validate_schema(metadata)
                fields = config.COLUMNS[1:]  # id: DB-generated, exactly 19 INSERT columns
                values = [tuple(typed_value(row.get(field), field, metadata[field]) for field in fields)
                          for row in rows or []]
                if values:
                    statement = sql.SQL("INSERT INTO {}.{} ({}) VALUES ({})").format(
                        sql.Identifier(table[0]), sql.Identifier(table[1]),
                        sql.SQL(",").join(map(sql.Identifier, fields)),
                        sql.SQL(",").join(sql.Placeholder() for _ in fields))
                    cursor.executemany(statement, values)
        # Return schema facts only, never defaults/connection/SQL values.
        return {"columns": {key: {k: v for k, v in value.items() if k != "udt"}
                             for key, value in metadata.items() if key in config.COLUMNS},
                "inserted": len(rows or [])}
    finally:
        connection.close()
